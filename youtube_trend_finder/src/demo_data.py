def _video(
    video_id: str,
    title: str,
    channel: str,
    subs: int | None,
    views: int,
    hours_ago: float,
    now: datetime,
    likes: int,
    comments: int,
    duration: int = 46,
) -> dict:
    return {
        "video_id": video_id,
        "title": title,
        "channel_id": "UC" + channel,
        "channel_name": channel,
        "published_at": isoformat_utc(now - timedelta(hours=hours_ago)),
        "duration_seconds": duration,
        "views": views,
        "likes": likes,
        "comments": comments,
        "subscriber_count": subs,
        "channel_total_views": (subs or 10000) * 40,
        "channel_video_count": 120,
        "description": "デモ用の説明です #shorts",
        "thumbnail_url": "",
        "from_short_search": True,
    }


